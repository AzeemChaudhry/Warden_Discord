"""Generate docs/SETTINGS.md from the settings registry.

python -m warden.docs          # rewrite the file
python -m warden.docs --check  # exit 1 if it's out of date (used in CI)
"""

from __future__ import annotations

import sys
from itertools import groupby
from pathlib import Path

# Importing the cogs registers every setting.
from .cogs import automod, config, leveling, moderation, onboarding, perks  # noqa: F401
from .settings import REGISTRY, Setting, SettingType

OUTPUT = Path(__file__).resolve().parent.parent / "docs" / "SETTINGS.md"

_TYPE_HINT = {
    SettingType.BOOL: "`true` / `false`",
    SettingType.INT: "number",
    SettingType.STRING: "text",
    SettingType.CHANNEL: "#channel",
    SettingType.ROLE: "@role",
    SettingType.LIST: "comma-separated list",
}


def _default(setting: Setting) -> str:
    value = setting.default
    if value is None:
        return "*not set*"
    if isinstance(value, bool):
        return "`true`" if value else "`false`"
    if isinstance(value, list):
        return f"`{', '.join(value)}`" if value else "*empty*"
    return f"`{value}`"


def _type(setting: Setting) -> str:
    hint = _TYPE_HINT[setting.type]
    if setting.min_value is not None or setting.max_value is not None:
        lo = setting.min_value if setting.min_value is not None else "…"
        hi = setting.max_value if setting.max_value is not None else "…"
        hint += f" ({lo}–{hi})"
    return hint


def render() -> str:
    lines = [
        "# Settings reference",
        "",
        "<!-- Generated by `python -m warden.docs`. Do not edit by hand. -->",
        "",
        "Every setting is stored per server. Change one with `/config set key:<key> value:<value>`,",
        "see current values with `/config view`, and restore a default with `/config reset`.",
        "",
    ]
    keys = sorted(REGISTRY)
    for module, group in groupby(keys, key=lambda k: k.split(".", 1)[0]):
        lines += [
            f"## {module.title()}",
            "",
            "| Key | Type | Default | Description |",
            "| --- | --- | --- | --- |",
        ]
        for key in group:
            s = REGISTRY[key]
            description = s.description.replace("|", "\\|")
            lines.append(f"| `{key}` | {_type(s)} | {_default(s)} | {description} |")
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    content = render()
    if "--check" in argv:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            print(f"{OUTPUT.name} is out of date. Run: python -m warden.docs")
            return 1
        print(f"{OUTPUT.name} is up to date.")
        return 0
    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text(content)
    print(f"Wrote {OUTPUT} ({len(REGISTRY)} settings)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
